PROCEDURE       REPAIR_UNDO_R	(DATA IN VARCHAR2,EMP_NO IN VARCHAR2, RES OUT VARCHAR2)
AS
p_MO   	  		VARCHAR2(25);
p_MODEL   		VARCHAR2(25);
p_WORKDATE		VARCHAR2(8);		-- LAST TIME WORK DATE
p_WORKSECTION NUMBER(2,0);	   		-- LAST TIME WORK SECTION
p_LINE 		  VARCHAR2(8);			-- LAST TIME PROD LINE
p_SECTION 	  VARCHAR2(16);			-- LAST TIME LINE SECTION
p_GROUP 	  VARCHAR2(16);			-- LAST TIME  STATION GROUP
p_STATION	  VARCHAR2(16);			-- LAST TIME WORK STATION
p_TYPE		  VARCHAR2(5);
p_CWDATE	  DATE;					-- CURRENT WORK DATE AND TIME
p_ERRCNT	  NUMBER(1,0);			-- CHECK HOW TO UNDO THE STATISTICS DATA ON SFISM4.R_STATION_REC_T
p_ECNPASS 	  NUMBER(1,0);			-- WHEN IT IS THE RMA 	NOT USED HERE
p_ENCVAL 	  NUMBER(2,0);			-- NOT USED HERE

p_ROUTECODE	  NUMBER(4,0);			-- CURRENT USED ROUTE CODE
p_ERRFLAG	  VARCHAR2(1);			-- ERROR FLAG OF THE WIP
p_NEXTGROUP	  VARCHAR2(16);			-- NEXT TEST GROUP NAME
p_NEXTSTATION VARCHAR2(16);			-- NEXT TEST STATION NAME

BEGIN

	 RES:='';

	 p_CWDATE:=SYSDATE;

	 SELECT MO_NUMBER,MODEL_NAME,NVL(TYPE,''),TO_CHAR(IN_STATION_TIME,'YYYYMMDD'),TO_CHAR(IN_STATION_TIME,'HH24'),
	 		LINE_NAME,SECTION_NAME,GROUP_NAME, STATION_NAME,NVL(ENC_CNT,0),NVL(ECN_PASS_QTY,0),SPECIAL_ROUTE,ERROR_FLAG INTO
			p_MO,p_MODEL,p_TYPE,p_WORKDATE,p_WORKSECTION,p_LINE,p_SECTION,p_GROUP,p_STATION,p_ENCVAL,p_ECNPASS,p_ROUTECODE,p_ERRFLAG
	 FROM SFISM4.R_WIP_TRACKING_T
	 WHERE SERIAL_NUMBER=DATA;

	 SELECT GROUP_NEXT INTO p_NEXTGROUP
	 FROM SFIS1.C_ROUTE_CONTROL_T
	 WHERE ROUTE_CODE=p_ROUTECODE AND GROUP_NAME=p_GROUP AND STATE_FLAG=p_ERRFLAG AND ROWNUM=1;

	 SELECT STATION_NAME INTO p_NEXTSTATION
	 FROM SFIS1.C_STATION_CONFIG_T
	 WHERE LINE_NAME=p_LINE AND GROUP_NAME=p_NEXTGROUP AND ROWNUM=1;

	 SELECT COUNT(SERIAL_NUMBER) INTO p_ERRCNT FROM SFISM4.R_WIP_LOG_T
	 		WHERE SERIAL_NUMBER=DATA AND GROUP_NAME=p_GROUP AND MO_NUMBER=p_MO;


	 UPDATE SFISM4.R_REPAIR_T SET RECORD_TYPE='U',DUTY_TYPE='U',DUTY_STATION=p_STATION,REPAIR_STATUS='N',
	 		REPAIRER=EMP_NO,REPAIR_TIME=p_CWDATE,REASON_CODE='UNDO',REPAIR_STATION=p_NEXTSTATION
			WHERE SERIAL_NUMBER=DATA AND TEST_STATION=p_STATION AND REPAIR_STATUS IS NULL;


	 UPDATE SFISM4.R_WIP_TRACKING_T SET GROUP_NAME=p_NEXTGROUP,STATION_NAME=p_NEXTSTATION,ERROR_FLAG=0,IN_STATION_TIME=p_CWDATE,EMP_NO=EMP_NO
	 		WHERE SERIAL_NUMBER=DATA AND MO_NUMBER=p_MO AND ROWNUM=1;

	 IF p_ERRCNT=1 THEN

	 	UPDATE SFISM4.R_STATION_REC_T SET FAIL_QTY=FAIL_QTY-1,PASS_QTY=PASS_QTY+1
			   WHERE WORK_DATE=p_WORKDATE AND WORK_SECTION=p_WORKSECTION AND MO_NUMBER=p_MO
			   AND MODEL_NAME=p_MODEL AND LINE_NAME=p_LINE AND SECTION_NAME=p_SECTION
			   AND GROUP_NAME=p_GROUP;

	 ELSE


	 	 UPDATE SFISM4.R_STATION_REC_T SET REFAIL_QTY=FAIL_QTY-1,REPASS_QTY=REPASS_QTY+1
			   		 WHERE WORK_DATE=p_WORKDATE AND WORK_SECTION=p_WORKSECTION AND MO_NUMBER=p_MO
			   		 AND MODEL_NAME=p_MODEL AND LINE_NAME=p_LINE AND SECTION_NAME=p_SECTION
			   		 AND GROUP_NAME=p_GROUP;


	 END IF;

	 COMMIT;

	 RES:='OK';

EXCEPTION
		  WHEN NO_DATA_FOUND THEN
		  	   RES:='NO DATA FOUND!';

		  WHEN OTHERS THEN
		  	   BEGIN
		  	   		ROLLBACK;
			   		RES:='UNDO FAILED!';
			   END;
END;