PROCEDURE       CHECK_FIXTURE_MODEL_DCCS (
  DATA      IN    VARCHAR2,
  ASN       IN    VARCHAR2,
  LINE      IN    VARCHAR2,
  MYGROUP   IN    VARCHAR2,
  SECTION   IN    VARCHAR2,
  W_STATION IN    VARCHAR2,
  EMP       IN    VARCHAR2,
  RES       OUT   VARCHAR2
) AS

  SNSS          NUMBER;
  MODELS        VARCHAR(20);
  INPUTMODELS   VARCHAR(50);
  ERROR_SN EXCEPTION;
  ERROR_MODELS EXCEPTION;
  E_ERROR EXCEPTION;

