        -- Insert_Lsa_Alarm_H( LINE ,MYGROUP,3 ,RES);
        -- RES:='LINE START';
	--  ELSE

   IF S_STATE=1 THEN
        RES:='CLINE STOP '	;
	ELSIF S_STATE=2 THEN
	 RES:='SLINE STOP '	;
	ELSIF S_STATE=3 THEN
	 RES:='CSLINE STOP '	;
    ELSIF S_STATE=4 THEN
	 RES:='PLINE STOP '	;
	ELSIF S_STATE=5 THEN
	 RES:='CPLINE STOP '	;
	ELSE
	  RES:='SPLINE STOP '	;


	END IF ;
 EXCEPTION
   WHEN OTHERS THEN
    RES:='OK';



END;