BEGIN


  SELECT GROUP_NAME,STATE  INTO S_GROUP,S_STATE  FROM SFISM4.R_LSA_STOP_H
                                                                             WHERE LINE_NAME=LINE
																   AND    GROUP_NAME=MYGROUP
																			   AND  ROWNUM=1;
 --   SELECT count(*) INTO T_EMP_NO FROM SFIS1.C_LSA_EMP WHERE PRIVILEGE=LINE AND EMP_NO=DATA AND ROWNUM=1;
  --    IF T_EMP_NO>0 THEN
